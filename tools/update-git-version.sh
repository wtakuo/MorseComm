#!/bin/sh
# Write the git commit hash to git_version.h (shown on the splash screen and
# by show). Run before building.
# Rewrite only when the content changes (avoids triggering recompilation
# otherwise).
# If there are uncommitted changes, append "+" to the hash.
cd "$(git rev-parse --show-toplevel)" || exit 0
hash=$(git rev-parse --short=7 HEAD 2>/dev/null || echo unknown)
git diff --quiet HEAD -- . ':!git_version.h' 2>/dev/null || hash="$hash+"
new="// Generated by tools/update-git-version.sh. Do not edit.
#define GIT_COMMIT \"$hash\""
[ -f git_version.h ] && [ "$(cat git_version.h)" = "$new" ] && exit 0
printf '%s\n' "$new" > git_version.h
